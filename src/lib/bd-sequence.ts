/**
 * Create a sequence on the back of the wizard's first send. Called from
 * /api/admin/bd/wizard/send AFTER the first outbound has been dispatched
 * successfully and the OutreachMessage row has been written.
 *
 * Behavior:
 *   - If an active sequence already exists for (brand, contact, rep),
 *     no-op and return it. This is the second-time-the-rep-uses-the-
 *     wizard-on-the-same-contact case.
 *   - Otherwise create a sequence with one step per CadenceStep:
 *       step 0 (LI connect)  → status=skipped (we already opened with email)
 *       step 1 (email)       → status=sent, sentAt=now (the wizard just sent it)
 *       steps 2+             → status=pending, scheduledFor = startedAt + offset
 *
 * The transaction is passed in so the caller can commit it alongside the
 * wizard's own atomic writes.
 */
export async function createSequenceForFirstSend(opts: {
  tx: any; // Prisma transaction client
  brandId: string;
  contactId: string;
  repId: string;
  startedAt: Date;
  outreachMessageId?: string | null;
  /** Subject + body of the email that just went out — copied onto step 1 for history. */
  firstEmailSubject?: string | null;
  firstEmailBody?: string | null;
  cadenceKey?: string;
}) {
  const tx = opts.tx;
  const cadenceKey = opts.cadenceKey || "default";
  const cadence = getCadence(cadenceKey);

  // Bail if there's already an active sequence for this (brand, contact, rep).
  const existing = await tx.bDSequence.findFirst({
    where: {
      brandId: opts.brandId,
      contactId: opts.contactId,
      repId: opts.repId,
      status: "active",
    },
  });
  if (existing) return existing;

  const totalSteps = cadence.length;

  const seq = await tx.bDSequence.create({
    data: {
      brandId: opts.brandId,
      contactId: opts.contactId,
      repId: opts.repId,
      cadenceKey,
      status: "active",
      startedAt: opts.startedAt,
      totalSteps,
      sentSteps: 1, // step 1 (email) is sent
      skippedSteps: 1, // step 0 (LI connect) is skipped
    },
  });

  await Promise.all(
    cadence.map((step) => {
      const scheduledFor = new Date(
        opts.startedAt.getTime() + step.offsetDays * 24 * 60 * 60 * 1000,
      );

      // Step 0: LI connect — auto-skipped (we opened with email instead).
      if (step.index === 0) {
        return tx.bDSequenceStep.create({
          data: {
            sequenceId: seq.id,
            stepIndex: step.index,
            channel: step.channel,
            status: "skipped",
            scheduledFor,
            skippedAt: opts.startedAt,
            failReason: "Wizard opened with email — LinkedIn connect skipped at sequence creation.",
          },
        });
      }

      // Step 1: the email that just went out.
      if (step.index === 1) {
        return tx.bDSequenceStep.create({
          data: {
            sequenceId: seq.id,
            stepIndex: step.index,
            channel: step.channel,
            status: "sent",
            scheduledFor,
            sentAt: opts.startedAt,
            draftSubject: opts.firstEmailSubject || null,
            draftBody: opts.firstEmailBody || null,
            outreachMessageId: opts.outreachMessageId || null,
          },
        });
      }

      // Steps 2+: pending, waiting for the cron to tick them ready.
      return tx.bDSequenceStep.create({
        data: {
          sequenceId: seq.id,
          stepIndex: step.index,
          channel: step.channel,
          status: "pending",
          scheduledFor,
        },
      });
    }),
  );

  return seq;
}

/**
 * Mark a step as sent and recompute sequence counters. If this was the
 * last non-terminal step, mark the sequence completed. Caller must run
 * inside a transaction.
 */
export async function markStepSent(opts: {
  tx: any;
  stepId: string;
  outreachMessageId?: string | null;
  draftSubject?: string | null;
  draftBody?: string | null;
}) {
  const step = await opts.tx.bDSequenceStep.update({
    where: { id: opts.stepId },
    data: {
      status: "sent",
      sentAt: new Date(),
      outreachMessageId: opts.outreachMessageId ?? undefined,
      draftSubject: opts.draftSubject ?? undefined,
      draftBody: opts.draftBody ?? undefined,
    },
  });
  await recomputeSequenceCounters(opts.tx, step.sequenceId);
  return step;
}

/** Mark a step as skipped (rep declined to send) and bump counters. */
export async function markStepSkipped(opts: { tx: any; stepId: string; reason?: string }) {
  const step = await opts.tx.bDSequenceStep.update({
    where: { id: opts.stepId },
    data: {
      status: "skipped",
      skippedAt: new Date(),
      failReason: opts.reason || null,
    },
  });
  await recomputeSequenceCounters(opts.tx, step.sequenceId);
  return step;
}

/** Mark a step as failed (send error) and bump counters. */
export async function markStepFailed(opts: { tx: any; stepId: string; reason: string }) {
  const step = await opts.tx.bDSequenceStep.update({
    where: { id: opts.stepId },
    data: {
      status: "failed",
      failedAt: new Date(),
      failReason: opts.reason,
    },
  });
  await recomputeSequenceCounters(opts.tx, step.sequenceId);
  return step;
}

/**
 * Recompute sentSteps + skippedSteps + completion state for a sequence.
 * Called whenever a step changes terminal state. We do this server-side
 * rather than incrementing in place because the transaction guarantees
 * consistency even if multiple steps fire in parallel from cron.
 */
export async function recomputeSequenceCounters(tx: any, sequenceId: string) {
  const steps = await tx.bDSequenceStep.findMany({
    where: { sequenceId },
    select: { status: true },
  });
  const sent = steps.filter((s) => s.status === "sent").length;
  const skipped = steps.filter((s) => s.status === "skipped").length;
  const failed = steps.filter((s) => s.status === "failed").length;
  const terminal = sent + skipped + failed;
  const total = steps.length;

  const update: any = { sentSteps: sent, skippedSteps: skipped };
  if (terminal === total) {
    update.status = "completed";
    update.completedAt = new Date();
  }
  await tx.bDSequence.update({ where: { id: sequenceId }, data: update });
}

/**
 * Used by the wizard send route to detect "this is a follow-up step send,
 * not a brand-new outbound" — if the rep is sending against a step that
 * already exists, we mark the step sent rather than re-creating a sequence.
 */
export async function findStepForSend(opts: { brandId: string; contactId: string; repId: string }) {
  const seq = await prisma.bDSequence.findFirst({
    where: {
      brandId: opts.brandId,
      contactId: opts.contactId,
      repId: opts.repId,
      status: "active",
    },
    include: {
      steps: {
        where: { status: "ready", channel: { in: ["email", "linkedin_dm"] } },
        orderBy: { stepIndex: "asc" },
        take: 1,
      },
    },
  });
  return seq?.steps?.[0] || null;
}
