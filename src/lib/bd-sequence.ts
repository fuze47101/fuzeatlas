export const CADENCES: Record<string, CadenceStep[]> = {
  default: DEFAULT_CADENCE,
};

export function getCadence(key: string): CadenceStep[] {
  return CADENCES[key] || DEFAULT_CADENCE;
}

/** Hours between sequence ticks. The cron schedule in vercel.json should match. */
