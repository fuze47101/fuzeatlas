/**
 * ═══════════════════════════════════════════════════════════════════════
 * BD WIZARD PHASE 3 — Sequence engine
 *
 * A "sequence" is a multi-step outbound campaign one rep runs against one
 * contact at one brand. Cadences live in this file as plain TypeScript
 * data — adding a new cadence means adding a key to CADENCES, no schema
 * change required.
 *
 * The sequence engine is intentionally "stupid": each step has a single
 * scheduledFor timestamp. A cron at /api/cron/bd-sequence-tick walks
 * the table every hour, finds steps whose scheduledFor has passed, and
 * either:
 *   - generates a draft + creates a CrmTask (email, linkedin_dm, linkedin_connect, tradeshow)
 *   - executes the side effect immediately (paid → flag the brand)
 *
 * Per Andrew's locked decision (2026-04-20): "Always queue for review —
 * no auto-send ever". So even email steps just generate a draft and
 * park it on /acm/tasks. The rep clicks through to the wizard and hits
 * Send themselves. This file does NOT send anything.
 * ═══════════════════════════════════════════════════════════════════════
 */

import { prisma } from "@/lib/prisma";

/**
 * One step in a cadence. offsetDays is from sequence start (= when the rep
 * sent the first email via the wizard). Step 0 is always day 0.
 *
 * Channels:
 *   - "email"            — auto-drafted, queued for rep review
 *   - "linkedin_connect" — manual reminder; rep sends connect request in LI
 *   - "linkedin_dm"      — auto-drafted text; rep pastes into LI manually
 *   - "paid"             — system flips Brand.paidAudienceTagged = true
 *   - "tradeshow"        — manual reminder; "invite to next show"
 */
export type CadenceChannel = "email" | "linkedin_connect" | "linkedin_dm" | "paid" | "tradeshow";

export interface CadenceStep {
  index: number;
  channel: CadenceChannel;
  offsetDays: number;
  /** Short title for the rep-facing CrmTask. */
  taskTitle: (brandName: string, contactName: string) => string;
  /** Whether this step needs a draft generated by AI. */
  needsDraft: boolean;
  /** Whether this step auto-completes (no rep action needed). */
  autoComplete: boolean;
}

const lcName = (c: { firstName?: string; name?: string }) =>
  c.firstName || (c.name ? c.name.split(" ")[0] : "contact");

/**
 * The default 6-step long funnel — locked by Andrew on 2026-04-20.
 *
 *   D0  LI connect       manual          rep sends connect request in LI
 *   D2  Email             auto-drafted    THIS IS THE WIZARD'S FIRST SEND
 *   D5  LI DM             auto-drafted    rep pastes the text into LI
 *   D9  Email follow-up   auto-drafted    rep reviews + sends from wizard
 *   D14 Paid retargeting  system          flag the brand for ad audience
 *   D30 Tradeshow         manual          invite at next relevant show
 *
 * Day 0 is the day the wizard fired its first email. The LI connect step
 * is auto-skipped at sequence creation since the rep has already kicked
 * off contact via email — keeping it in the cadence so the dashboard
 * shows the full intended funnel even when steps got short-circuited.
 */
